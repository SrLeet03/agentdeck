#!/usr/bin/env bash
# Writes Formula/agentdeck.rb for a published release tag, using the release's checksums.txt.
# usage: scripts/update-formula.sh v0.2.0
set -euo pipefail

tag="${1:?usage: $0 <tag>}"
version="${tag#v}"
repo="SrLeet03/agentdeck"
base="https://github.com/${repo}/releases/download/${tag}"

sums="$(curl -fsSL "${base}/checksums.txt")"
sha() {
	local file="deck_${version}_$1.tar.gz"
	local s
	s="$(printf '%s\n' "$sums" | awk -v f="$file" '$2 == f { print $1 }')"
	[ -n "$s" ] || { echo "no checksum for $file" >&2; exit 1; }
	echo "$s"
}

# Resolve every checksum first: a failure inside the heredoc's $(...) would not stop the script.
sha_darwin_arm64="$(sha darwin_arm64)"
sha_darwin_amd64="$(sha darwin_amd64)"
sha_linux_arm64="$(sha linux_arm64)"
sha_linux_amd64="$(sha linux_amd64)"

mkdir -p Formula
cat > Formula/agentdeck.rb <<EOF
# Generated by scripts/update-formula.sh for ${tag}; do not edit by hand.
class Agentdeck < Formula
  desc "Terminal dashboard for Claude Code, Codex and Pi sessions"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/deck_${version}_darwin_arm64.tar.gz"
      sha256 "${sha_darwin_arm64}"
    end
    on_intel do
      url "${base}/deck_${version}_darwin_amd64.tar.gz"
      sha256 "${sha_darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/deck_${version}_linux_arm64.tar.gz"
      sha256 "${sha_linux_arm64}"
    end
    on_intel do
      url "${base}/deck_${version}_linux_amd64.tar.gz"
      sha256 "${sha_linux_amd64}"
    end
  end

  def install
    bin.install "deck"
  end

  test do
    assert_match "deck v#{version}", shell_output("#{bin}/deck version")
  end
end
EOF
echo "wrote Formula/agentdeck.rb for ${tag}"
